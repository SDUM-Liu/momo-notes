test('six-digit authenticator codes, clock mismatch and replay', () => {
  const { totp, verify } = require('../shared/authenticator.mjs')
  const seed = Buffer.from('12345678901234567890')
  // RFC 6238 Appendix B, SHA-1 results truncated to six digits.
  for (const [seconds, code] of [[59,'287082'],[1111111109,'081804'],[1234567890,'005924'],[2000000000,'279037']]) {
    const step = Math.floor(seconds / 30)
    assert.equal(totp(seed,step),code)
    assert.equal(verify(seed,code,-1,seconds*1000),step)
    assert.throws(() => verify(seed,code,step,seconds*1000),/已经使用/)
    assert.equal(verify(seed,code,-1,(seconds+30)*1000),step)
    assert.throws(() => verify(seed,code,-1,(seconds+120)*1000),/时间不一致/)
  }
  assert.equal(verify(seed,'２８７ ０８２',-1,59000),1)
})

test('protected book, authenticated backup and interrupted desktop handoff', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'momo-migration-'))
  try {
    const a = path.join(root, 'a'), b = path.join(root, 'b')
    const store = openStore(a); openStore(b)
    const book = privateBook(a), password = 'correct horse battery staple'
    const { uri } = book.call('begin')
    book.lock()
    assert.equal(book.call('begin').uri, uri)
    const bits = new URL(uri).searchParams.get('secret').split('').map(c => 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567'.indexOf(c).toString(2).padStart(5, '0')).join('')
    const secret = Buffer.from(bits.match(/.{8}/g).map(x => parseInt(x, 2))).toString('base64')
    const code = token(secret, Math.floor(Date.now() / 30000))
    assert.deepEqual(book.call('unlock', { password, code }), [])
    book.call('save', { entries: [{ title: 'sensitive text', tab: 2, text: 'topic' }] }); book.lock()
    assert.throws(() => book.call('save', { entries: [] }))
    const encrypted = fs.readFileSync(path.join(a, 'private-book.enc'), 'utf8')
    assert(!encrypted.includes('sensitive text'))
    assert.throws(() => privateBook(a).call('unlock', { password, code }), /已经使用/)
    store.saveNote('2026-11-22', { type: 'doc', content: [{ type: 'paragraph', content: [{ type: 'text', text: 'a'.repeat(350000) }] }] })
    const snapshot = () => migration.snapshot(a, store, {})
    const exportFile = migration.pack(snapshot(), password)
    assert.throws(() => migration.unpack(exportFile, 'another passphrase'))
    assert.deepEqual(migration.unpack(exportFile, password), snapshot())
    const sync = createSync(a, store, null, () => {})
    sync.setEnabled(true, 'http://localhost:3456', '')
    sync.status('online', sync.link().room)
    const pair = sync.code()
    const follower = { code: '', setPair(value) { this.code = value; this.store = true } }
    const sender = () => handoff({ root: a, directory: a, sync, follower, snapshot, credentials: {}, check() {}, restart() {} })
    const receiver = () => handoff({ root: b, directory: migration.activePath(b), sync: {}, follower: { code: pair }, credentials: {}, check() {}, restart() {} })
    let dest = receiver(), source = sender()
    const link = dest.ready()
    const rpc = (op, data = {}) => {
      const id = transferId()
      const result = unseal(link.key, 'handoff/' + id, dest.receive(seal(link.key, 'handoff', { id, op, ...data })))
      assert(!result.error, result.error); return result.value
    }
    assert.throws(() => source.prepare(link.code, 'wrong'), /尚未绑定/)
    const { checksum, count } = source.prepare(link.code, rpc('hello').proof)
    assert(count > 1)
    for (let index = 0; index < count; index++) rpc('chunk', { checksum, index, chunk: source.chunk(index) })
    assert.equal(rpc('stage', { checksum }).staged, checksum)
    assert.equal(migration.activePath(b), b)
    source.cutover(link.code, checksum)
    assert.equal(sync.state().enabled, false); assert.equal(follower.code, pair)
    assert.equal(sync.owns(require('../shared/sync.mjs').parsePairing(pair).key), false)
    source = sender(); dest = receiver()
    assert.equal(source.pending().checksum, checksum)
    assert(rpc('activate', { checksum }).done)
    dest = receiver()
    assert(rpc('activate', { checksum }).done)
    const promoted = migration.activePath(b)
    assert.deepEqual(openStore(promoted).data.notes, store.data.notes)
    assert.equal(fs.readFileSync(path.join(promoted, 'private-book.enc'), 'utf8'), encrypted)
    assert.equal(JSON.parse(fs.readFileSync(path.join(promoted, 'sync.json'))).enabled, true)
    source.finish(checksum)
    assert.equal(source.pending(), null)
  } finally { fs.rmSync(root, { recursive: true, force: true }) }
})
