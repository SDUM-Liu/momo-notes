const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { randomBytes, randomUUID } = require('node:crypto')
const { privateBook, token } = require('../desktop/private-book.cjs')
const { remoteBook } = require('../desktop/remote-book.cjs')
const { derive, encrypt } = require('../desktop/sealed.cjs')
const { diskMedia, chunkSize } = require('../desktop/disk-media.cjs')
const phone = randomUUID(), other = randomUUID()
const password = 'test vault password only'
const locked = error => error.code === 'PRIVATE_LOCKED'

function fixture(t, {entries = [], enrolled = true} = {}) {
  t.mock.timers.enable({apis:['setTimeout','Date'],now:1_800_000_000_000})
  const dir = fs.mkdtempSync(path.join(os.tmpdir(),'momo-remote-book-'))
  const filename = path.join(dir,'private-book.enc')
  const secret = randomBytes(20).toString('base64')
  if (enrolled) {
    const salt = randomBytes(16), key = derive(password,salt)
    fs.writeFileSync(filename,JSON.stringify(encrypt(key,salt,{entries,last:-1,secret},'momo/private-book/v1')))
    key.fill(0)
  }
  const state = {busy:false}
  const book = privateBook(dir), remote = remoteBook(book,{isBusy:()=>state.busy})
  t.after(() => { remote.forceLock(); fs.rmSync(dir,{recursive:true,force:true}) })
  const auth = () => ({password,code:token(secret,Math.floor(Date.now()/30000)),attempt:randomUUID()})
  const call = (op,args={},owner=phone) => remote.call(owner,op,args)
  return {remote,book,call,auth,state,dir,filename,secret}
}

test('remote enrollment is unavailable and cannot interrupt the local authenticator dialog', t => {
  const {remote,call,auth,filename} = fixture(t,{enrolled:false})
  assert.throws(()=>call('begin'),/在主设备/)
  assert.throws(()=>call('unlock',auth()),/在主设备/)
  const enrollment = remote.local('begin')
  assert.match(enrollment.uri,/^otpauth:/)
  assert.throws(()=>call('begin'),/在主设备/)
  assert.throws(()=>call('lock',{}),locked)
  assert.equal(remote.local('begin').uri,enrollment.uri)
  assert.equal(fs.existsSync(filename),false)
})

test('local and remote owners cannot view, lock, or interrupt each other and expired grants cannot be reused', t => {
  const {remote,book,call,auth,state} = fixture(t)
  const credentials = auth()
  assert.deepEqual(remote.local('begin'),{})
  assert.throws(()=>call('unlock',credentials),/正在使用/)
  assert.deepEqual(remote.local('unlock',credentials),[])
  assert.throws(()=>call('begin'),/正在使用/)
  assert.throws(()=>call('lock',{session:'wrong'}),locked)
  assert(book.unlocked)
  remote.revoke()
  assert(book.unlocked)
  remote.localLock()
  t.mock.timers.tick(30000)
  state.busy = true
  assert.throws(()=>call('unlock',auth()),/AI 任务/)
  state.busy = false
  const fresh = auth()
  assert.deepEqual(call('begin'),{})
  const first = call('unlock',fresh)
  assert.match(first.session,/^[0-9a-f]{64}$/)
  assert.equal(first.size,2)
  assert.deepEqual(call('unlock',fresh),first)
  assert.throws(()=>call('unlock',{...fresh,password:'changed password'}),/正在使用/)
  assert.throws(()=>call('unlock',fresh,other),/正在使用/)
  assert.throws(()=>call('manifestRead',{...first,index:0},other),locked)
  assert.throws(()=>call('lock',{...first},other),locked)
  assert.throws(()=>call('manifestRead',{session:'wrong',index:0}),locked)
  assert.throws(()=>remote.local('begin'),/已配对的设备/)
  assert.throws(()=>remote.local('mediaInfo',{id:randomUUID()}),/已配对的设备/)
  remote.local('lock')
  remote.localLock()
  remote.revoke(other)
  assert(remote.active)
  assert.deepEqual(call('manifestRead',{...first,index:0}),{bytes:Buffer.from('[]').toString('base64')})
  t.mock.timers.tick(5*60000-1000)
  call('manifestRead',{...first,index:0})
  t.mock.timers.tick(2000)
  assert(remote.active)
  t.mock.timers.tick(5*60000)
  assert(!book.unlocked)
  assert(!remote.active)
  assert.throws(()=>call('manifestRead',{...first,index:0}),locked)
  const second = call('unlock',auth(),other)
  assert.notEqual(first.session,second.session)
  remote.forceLock()
  assert(!book.unlocked)
  assert.throws(()=>call('manifestRead',{...second,index:0},other),locked)
})

test('remote authentication backoff survives disconnects, begin calls and owner changes', t => {
  const {remote,call,auth} = fixture(t)
  const bad = {...auth(),password:'wrong test password'}
  assert.throws(()=>call('unlock',bad),/口令/)
  call('begin',{},other)
  remote.revoke()
  remote.forceLock()
  assert.throws(()=>call('unlock',auth(),other),/频繁/)
  t.mock.timers.tick(1500)
  assert.throws(()=>call('unlock',bad,other),/口令/)
  t.mock.timers.tick(1600)
  assert.throws(()=>call('unlock',auth()),/频繁/)
  t.mock.timers.tick(1400)
  assert(call('unlock',auth()).session)
})

test('bounded manifest and attachment blocks preserve data across saves and discard interrupted writes on revocation', t => {
  const marker = '密'.repeat(chunkSize/3+10)
  const entries = [{kind:'fixed-pages-v1',files:[],notes:{fixture:marker}}]
  const {call,auth,remote,dir,filename,secret} = fixture(t,{entries})
  const {session,size} = call('unlock',auth())
  function readManifest() {
    const chunks = []
    for (let index=0;index<Math.ceil(size/chunkSize);index++) {
      const raw = Buffer.from(call('manifestRead',{session,index}).bytes,'base64')
      assert(raw.length<=chunkSize)
      chunks.push(raw)
    }
    return JSON.parse(Buffer.concat(chunks))
  }
  assert.deepEqual(readManifest(),entries)
  assert(!JSON.stringify(readManifest()).includes(secret))
  const f = {id:randomUUID(),size:chunkSize+9,mime:'video/mp4',storage:'chunks-v1',name:'fixture video.mp4'}
  const blocks = [randomBytes(chunkSize),randomBytes(9)]
  call('mediaBegin',{session,...f})
  assert.throws(()=>call('mediaWrite',{session,id:f.id,index:0,bytes:'A'.repeat(chunkSize*2)}),/数据块/)
  for (const [index,raw] of blocks.entries()) call('mediaWrite',{session,id:f.id,index,bytes:raw.toString('base64')})
  call('mediaFinish',{session,id:f.id})
  assert.throws(()=>call('mediaRead',{session,id:f.id,index:0}),/文件列表/)
  entries[0].files.push(f)
  const data = Buffer.from(JSON.stringify(entries))
  call('saveBegin',{session,size:data.length})
  assert.throws(()=>call('saveWrite',{session,index:1,bytes:'AA=='}),/顺序/)
  call('saveWrite',{session,index:0,bytes:data.subarray(0,chunkSize).toString('base64')})
  assert.throws(()=>call('saveCommit',{session}),/尚未完成/)
  call('saveWrite',{session,index:1,bytes:data.subarray(chunkSize).toString('base64')})
  call('saveCommit',{session})
  assert.deepEqual(call('mediaInfo',{session,id:f.id}),{size:f.size,mime:f.mime})
  assert.deepEqual(Buffer.from(call('mediaRead',{session,id:f.id,index:0}).bytes,'base64'),blocks[0])
  assert.deepEqual(Buffer.from(call('mediaRead',{session,id:f.id,index:1}).bytes,'base64'),blocks[1])
  assert.throws(()=>call('mediaRead',{session,id:f.id,index:2}),/分块/)
  assert.throws(()=>call('mediaRemove',{session,id:f.id}),/先保存/)
  assert.throws(()=>call('mediaPreview',{session,id:f.id}),/未知/)
  assert(!fs.readFileSync(filename).includes('fixture video.mp4'))
  const disk = diskMedia(dir)
  assert(!disk.readRaw(f.id,0).includes(blocks[0].subarray(0,64)))
  const interrupted = {...f,id:randomUUID()}
  call('mediaBegin',{session,...interrupted})
  call('mediaWrite',{session,id:interrupted.id,index:0,bytes:blocks[0].toString('base64')})
  call('saveBegin',{session,size:chunkSize+1})
  call('saveWrite',{session,index:0,bytes:Buffer.alloc(chunkSize,32).toString('base64')})
  remote.revoke(phone)
  assert.throws(()=>call('saveCommit',{session}),locked)
  assert.throws(()=>call('mediaRead',{session,id:f.id,index:0}),locked)
  t.mock.timers.tick(30000)
  const newSession = call('unlock',auth()).session
  assert.throws(()=>call('saveCommit',{session:newSession}),/尚未完成/)
  call('mediaBegin',{session:newSession,...interrupted})
  call('mediaAbort',{session:newSession,id:interrupted.id})
  assert.deepEqual(disk.list().map(meta=>meta.id),[f.id])
  assert.deepEqual(call('mediaInfo',{session:newSession,id:f.id}),{size:f.size,mime:f.mime})
})
